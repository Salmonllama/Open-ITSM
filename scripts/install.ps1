# Installs Open ITSM on Windows for evaluation through Docker Desktop.
# Production hosting is supported on a Linux host or VM; see docs/OPERATIONS.md.
#
# Usage:
#   .\install.ps1 [-Dir .\open-itsm] [-Hostname localhost] [-Version 1.0.0] [-NoStart]
[CmdletBinding()]
param(
  [string]$Dir = ".\open-itsm",
  [string]$Hostname = "",
  [string]$Version = "1.0.0",
  [string]$Repo = "Salmonllama/Open-ITSM",
  [string]$Ref = "main",
  [switch]$InternalTls,
  [switch]$NoStart
)

$ErrorActionPreference = "Stop"

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  Write-Error "Docker Desktop is required but 'docker' was not found on PATH."
  exit 1
}

docker compose version *> $null
if ($LASTEXITCODE -ne 0) {
  Write-Error "Docker Compose v2 ('docker compose') is required."
  exit 1
}

New-Item -ItemType Directory -Force -Path $Dir | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $Dir "certs") | Out-Null
Push-Location $Dir

try {
  if (Test-Path ".env") {
    Write-Error "An existing .env file was found in $Dir. Refusing to overwrite existing secrets."
    exit 1
  }

  $baseUrl = "https://raw.githubusercontent.com/$Repo/$Ref"
  Write-Host "Downloading compose.yml and .env.example..."
  Invoke-WebRequest -UseBasicParsing -Uri "$baseUrl/compose.yml" -OutFile "compose.yml"
  Invoke-WebRequest -UseBasicParsing -Uri "$baseUrl/.env.example" -OutFile ".env.example"

  if (-not $Hostname) {
    $Hostname = Read-Host "Hostname to open in the browser (press Enter for localhost)"
    if (-not $Hostname) { $Hostname = "localhost" }
  }
  $Hostname = $Hostname -replace '^https?://', ''
  $Hostname = $Hostname.TrimEnd('/')

  $caddyGlobal = ""
  if ($InternalTls -or $Hostname -eq "localhost") {
    $caddyGlobal = "local_certs"
  }

  function New-RandomBytes([int]$Length) {
    $bytes = New-Object byte[] $Length
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return $bytes
  }

  $pgPassword = ([System.BitConverter]::ToString((New-RandomBytes 24)) -replace '-', '').ToLowerInvariant()
  $appSecret = [System.Convert]::ToBase64String((New-RandomBytes 32))
  $sessionSecret = [System.Convert]::ToBase64String((New-RandomBytes 48))

  $envContent = @"
# Generated by Open ITSM install.ps1
OPEN_ITSM_VERSION=$Version
APP_HOSTNAME=$Hostname
CADDY_GLOBAL_OPTIONS=$caddyGlobal
CADDY_TLS=
POSTGRES_PASSWORD=$pgPassword
APP_SECRET_KEY=$appSecret
SESSION_SECRET=$sessionSecret
BACKUP_RETENTION_DAYS=14
LOG_LEVEL=info
"@
  Set-Content -Path ".env" -Value $envContent -Encoding ASCII

  Write-Host ""
  Write-Host "Configuration written to $((Resolve-Path '.env').Path)."
  Write-Host "IMPORTANT: Save a copy of APP_SECRET_KEY in your password manager."

  if ($NoStart) {
    Write-Host "Skipping startup (-NoStart). Start later with: docker compose up -d"
    return
  }

  Write-Host ""
  Write-Host "Starting Open ITSM..."
  docker compose up -d

  Write-Host ""
  Write-Host "Open ITSM is starting at: https://$Hostname"
  Write-Host "Read the one-time setup token with: docker compose logs app"
} finally {
  Pop-Location
}
