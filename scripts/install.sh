#!/usr/bin/env bash
# Installs Open ITSM on Linux using Docker Compose.
#
# Usage:
#   curl -fsSL https://raw.githubusercontent.com/Salmonllama/Open-ITSM/main/scripts/install.sh | bash
#   ./scripts/install.sh [--dir /opt/open-itsm] [--hostname itsm.example.com] [--internal] [--version 1.0.0] [--no-start]
set -euo pipefail

REPO="${OPEN_ITSM_REPO:-Salmonllama/Open-ITSM}"
REF="${OPEN_ITSM_REF:-main}"
VERSION="${OPEN_ITSM_VERSION:-1.0.0}"
INSTALL_DIR="${OPEN_ITSM_DIR:-}"
HOSTNAME_ARG="${APP_HOSTNAME:-}"
INTERNAL_TLS="${OPEN_ITSM_INTERNAL_TLS:-}"
NO_START=0
LOCAL_SRC=""

while [ $# -gt 0 ]; do
  case "$1" in
    --dir) INSTALL_DIR="$2"; shift 2 ;;
    --hostname) HOSTNAME_ARG="$2"; shift 2 ;;
    --internal) INTERNAL_TLS=1; shift ;;
    --version) VERSION="$2"; shift 2 ;;
    --local) LOCAL_SRC="$2"; shift 2 ;;
    --no-start) NO_START=1; shift ;;
    -h|--help)
      sed -n '2,7p' "$0" | sed 's/^# \?//'
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      exit 2
      ;;
  esac
done

need() {
  if ! command -v "$1" >/dev/null 2>&1; then
    echo "Error: $1 is required but was not found on PATH." >&2
    exit 1
  fi
}

need docker
if ! docker compose version >/dev/null 2>&1; then
  echo "Error: Docker Compose v2 (docker compose) is required." >&2
  echo "Install Docker Engine with the compose plugin, then re-run this script." >&2
  exit 1
fi
need openssl
if [ -z "$LOCAL_SRC" ]; then
  need curl
fi

if [ -z "$INSTALL_DIR" ]; then
  if [ "$(id -u)" -eq 0 ]; then
    INSTALL_DIR="/opt/open-itsm"
  else
    INSTALL_DIR="$PWD/open-itsm"
  fi
fi

mkdir -p "$INSTALL_DIR/certs"
cd "$INSTALL_DIR"

if [ -f ".env" ]; then
  echo "Error: $INSTALL_DIR/.env already exists. Refusing to overwrite existing secrets." >&2
  echo "To upgrade an existing install, run: docker compose pull && docker compose up -d" >&2
  exit 1
fi

echo "Installing Open ITSM into $INSTALL_DIR..."

if [ -n "$LOCAL_SRC" ]; then
  cp "$LOCAL_SRC/compose.yml" ./compose.yml
  cp "$LOCAL_SRC/.env.example" ./.env.example
  if [ -f "$LOCAL_SRC/scripts/restore.sh" ]; then
    mkdir -p ./scripts
    cp "$LOCAL_SRC/scripts/restore.sh" ./scripts/restore.sh
    chmod +x ./scripts/restore.sh
  fi
else
  BASE_URL="https://raw.githubusercontent.com/${REPO}/${REF}"
  curl -fsSL "${BASE_URL}/compose.yml" -o ./compose.yml
  curl -fsSL "${BASE_URL}/.env.example" -o ./.env.example
  mkdir -p ./scripts
  curl -fsSL "${BASE_URL}/scripts/restore.sh" -o ./scripts/restore.sh
  chmod +x ./scripts/restore.sh
fi

if [ -z "$HOSTNAME_ARG" ]; then
  if [ -t 0 ]; then
    printf "Hostname users will open in the browser (e.g. itsm.example.com or localhost): "
    read -r HOSTNAME_ARG
  fi
fi
HOSTNAME_ARG="${HOSTNAME_ARG:-localhost}"
HOSTNAME_ARG="${HOSTNAME_ARG#https://}"
HOSTNAME_ARG="${HOSTNAME_ARG#http://}"
HOSTNAME_ARG="${HOSTNAME_ARG%/}"

if [ -z "$INTERNAL_TLS" ]; then
  if [ "$HOSTNAME_ARG" = "localhost" ]; then
    INTERNAL_TLS=1
  elif [ -t 0 ]; then
    printf "Is %s internal-only (not reachable from the internet for Let's Encrypt)? [y/N]: " "$HOSTNAME_ARG"
    read -r ans
    case "$ans" in
      y|Y|yes|YES) INTERNAL_TLS=1 ;;
      *) INTERNAL_TLS=0 ;;
    esac
  else
    INTERNAL_TLS=0
  fi
fi

CADDY_GLOBAL_OPTIONS=""
if [ "$INTERNAL_TLS" = "1" ]; then
  CADDY_GLOBAL_OPTIONS="local_certs"
fi

POSTGRES_PASSWORD="$(openssl rand -hex 24)"
APP_SECRET_KEY="$(openssl rand -base64 32)"
SESSION_SECRET="$(openssl rand -base64 48)"

umask 077
cat > .env <<EOF
# Generated by Open ITSM install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
OPEN_ITSM_VERSION=${VERSION}
APP_HOSTNAME=${HOSTNAME_ARG}
CADDY_GLOBAL_OPTIONS=${CADDY_GLOBAL_OPTIONS}
CADDY_TLS=
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
APP_SECRET_KEY=${APP_SECRET_KEY}
SESSION_SECRET=${SESSION_SECRET}
BACKUP_RETENTION_DAYS=14
LOG_LEVEL=info
EOF
chmod 600 .env

echo ""
echo "Configuration written to $INSTALL_DIR/.env (mode 600)."
echo "IMPORTANT: Store a copy of APP_SECRET_KEY in your password manager."
echo "Without it, stored Microsoft 365, Entra ID and chat credentials cannot be decrypted after a restore."

if [ "$NO_START" -eq 1 ]; then
  echo "Skipping startup (--no-start). Start later with: cd $INSTALL_DIR && docker compose up -d"
  exit 0
fi

echo ""
echo "Starting Open ITSM..."
docker compose up -d

echo "Waiting for Open ITSM to become healthy..."
for _ in $(seq 1 30); do
  if docker compose exec -T app node -e "fetch('http://127.0.0.1:3030/healthz').then(r=>process.exit(r.ok?0:1),()=>process.exit(1))" >/dev/null 2>&1; then
    break
  fi
  sleep 2
done

echo ""
echo "Open ITSM is running at: https://${HOSTNAME_ARG}"
echo ""
echo "First-run setup token (from docker compose logs app):"
docker compose logs app 2>/dev/null | grep -i "setup token" | tail -n 1 || echo "Run 'docker compose logs app' to read the one-time setup token."
